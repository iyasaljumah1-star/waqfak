test("tour", async ({ browser }, info) => {
  test.setTimeout(30 * 60_000);
  const vp = info.project.name;
  const pages = new Map<string, import("@playwright/test").Page>();
  const done: (Shot & { file: string })[] = [];
  for (const s of SHOTS) {
    let page = pages.get(s.role);
    if (!page) {
      const ctx = await browser.newContext(info.project.use as never);
      page = await ctx.newPage();
      if (s.role !== "guest") await loginAs(page, s.role);
      pages.set(s.role, page);
    }
    try {
      await page.goto(s.path, { waitUntil: "networkidle", timeout: 45_000 });
    } catch {}
    await page.waitForTimeout(400);
    const file = `img/${vp}-${s.id}.jpg`;
    await page.screenshot({ path: `${OUT}/${file}`, fullPage: true, type: "jpeg", quality: 72 });
    done.push({ ...s, file });
  }
  writeFileSync(`${OUT}/manifest-${vp}.json`, JSON.stringify(done, null, 1));
});
